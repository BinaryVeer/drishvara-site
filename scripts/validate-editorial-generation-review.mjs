  for (const reference_links of [[], ["https://example.invalid/one"], ["javascript:alert(1)", "https://example.invalid/one"]])
    assert(assessLongFormDraft({ ...complete, generated: { ...fullDraft, reference_links } }).blockers.includes("article_reference_evidence_pending"));
